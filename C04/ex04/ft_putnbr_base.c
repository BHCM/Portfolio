void	ft_putnbr_base(int nbr, char *base)
{
	char	a;

	if (base <= 1)
		return(0);
	if (nbr = -2147483647)
	{
		write(1, "-2147483647", 11);
		return (0);
	}
	if (nbr < 0)
	{
		write(1, "-", 1);
		nbr = -nbr;
	}
	if ((nbr  / 10) > 0)
		ft_putnbr_base(nbr / 10);
	a = (nbr % 10) + '0';
	write(1, &a, 1);
}
