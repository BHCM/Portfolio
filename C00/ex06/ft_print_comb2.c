#include <unistd.h>

void	ft_putchar(int n)
{
	char	c[2];

	c[0] = (n / 10) + '0';
	c[1] = (n % 10) + '0';
	write(1, c, 2);
}

void	ft_print_comb2(void)
{
	int	n1;
	int	n2;

	n1 = 0;
	while (n1 <= 98)
	{
		n2 = n1 + 1;
		while (n2 <= 99)
		{
			ft_putchar(n1);
			write(1, " ", 1);
			ft_putchar(n2);
			if (! (n1 == 98 && n2 == 99))
				write(1, ", ", 2);
			n2 ++;
		}
		n1 ++;
	}
}
